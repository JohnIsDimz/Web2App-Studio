    elements.forEach((el) => {
      const name = el.dataset.icon;
      // Coba feather dulu, fallback ke heroicons library
      let svg = '';
      if (ICONS[name]) {
        svg = render(name, el.dataset.iconClass || el.className || 'h-6 w-6');
      } else if (window.Web2AppIcons?.render) {
        // Fallback ke heroicons
        svg = window.Web2AppIcons.render(
          name,
          el.dataset.iconClass || el.className || 'h-6 w-6'
        );
      }
      el.innerHTML = svg;
    });
